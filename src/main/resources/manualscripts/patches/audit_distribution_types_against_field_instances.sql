-- 1. Summary: which instance and type combinations are not offered on screen?
SELECT pd.instance,
       pd.distribution_type,
       a.allowed_types                  types_offered_on_screen,
       count(*)                         affected_rows,
       count(DISTINCT sd.submission_id) affected_submissions
FROM remi.probability_distributions pd
JOIN remi.submission_details sd ON sd.id = pd.submission_detail_id
LEFT JOIN allowed a ON a.instance = pd.instance
WHERE pd.distribution_type IS NOT NULL
  AND (a.instance IS NULL OR NOT (pd.distribution_type = ANY (a.allowed_types)))
GROUP BY pd.instance, pd.distribution_type, a.allowed_types
ORDER BY affected_rows DESC, pd.instance, pd.distribution_type;

